// Функция за извличане на случаен Кан от конкретна династия
function getRandomKan(dynastyName) {
    const dynasty = bulgarianDynasties[dynastyName];
    if (!dynasty) return null;
    const allRulers = [...dynasty.rulers, ...(dynasty.branchRulers || [])];
    const randomRuler = allRulers[Math.floor(Math.random() * allRulers.length)];
    return { title: "Кан", name: randomRuler.name, years: randomRuler.years };
}

window.bulgarianDynasties = bulgarianDynasties;
window.getRandomKan = getRandomKan;
